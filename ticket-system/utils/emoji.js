/**
 * =========================================================
 *  utils/emoji.js
 * =========================================================
 * إيموجي آمن: يتحقق من صحة الإيموجي قبل استخدامه في الأزرار
 * والقوائم المنسدلة. يمنع أخطاء Discord API الناتجة عن إيموجي
 * مخصص غير صالح (مثل `<:name>` بدون آيدي) أو نص عشوائي.
 *
 * الصيغ المقبولة:
 *   - إيموجي يونيكود واحد: 🎫 👍
 *   - إيموجي مخصص صحيح:   <:name:123456789> أو <a:name:123456789>
 *
 * أي قيمة أخرى تعود إلى 🎫 كبديل آمن.
 * =========================================================
 */

/**
 * @param {String|undefined|null} input
 * @returns {String} إيموجي صالح أو 🎫
 */
function safeEmoji(input) {
    const str = String(input || '').trim();
    if (!str) return '🎫';

    // إيموجي مخصص صحيح: <:name:id> أو <a:name:id>
    if (/^<a?:\w+:\d+>$/.test(str)) return str;

    // إيموجي يونيكود واحد
    if (/^\p{Extended_Pictographic}$/u.test(str)) return str;

    // أي شيء آخر (نص عشوائي / إيموجي مخصص ناقص) → بديل آمن
    return '🎫';
}

module.exports = { safeEmoji };
